#!/usr/bin/env python3
"""Build the child-level obligation for tv80_mcode, and its null control.

tv80_mcode is purely combinational (derived by tools/gate_proposal.derive_ports:
6 inputs, 46 outputs, no clock, no reset). The obligation is therefore
combinational equivalence of gold against gate, **at Mode = 1**, the value
tv80s passes down through tv80_core (amendment 1, defect 3). Its own default is
Mode = 0 and it references Mode 42 times, so proving it at the default would
prove a different decoder.

Three variants of one miter, selected by a define, so the invariant assumption
is the only thing that differs between the plain and invariant tasks:

  plain    no assumption                         R95: expected not PROVEN
  inv      assume !(MCycle[5] && MCycle[6])      R91: expected PROVEN
  broken   inv's assumption, against a variant   R92: expected still REFUTED
           with one assignment deliberately wrong

The broken variant changes `Inc_PC = 1'b1` to `Inc_PC = 1'b0` in the transform's
2'b01 arm, a combination the assumption permits. If the assumption let this
through, it would be too strong and every verdict under it would be void.
"""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))

INS = [("IR", 8), ("ISet", 2), ("MCycle", 7), ("F", 8), ("NMICycle", 1), ("IntCycle", 1)]
OUTS = [("MCycles", 3), ("TStates", 3), ("Prefix", 2), ("Inc_PC", 1), ("Inc_WZ", 1),
        ("IncDec_16", 4), ("Read_To_Reg", 1), ("Read_To_Acc", 1), ("Set_BusA_To", 4),
        ("Set_BusB_To", 4), ("ALU_Op", 4), ("Save_ALU", 1), ("PreserveC", 1),
        ("Arith16", 1), ("Set_Addr_To", 3), ("IORQ", 1), ("Jump", 1), ("JumpE", 1),
        ("JumpXY", 1), ("Call", 1), ("RstP", 1), ("LDZ", 1), ("LDW", 1), ("LDSPHL", 1),
        ("Special_LD", 3), ("ExchangeDH", 1), ("ExchangeRp", 1), ("ExchangeAF", 1),
        ("ExchangeRS", 1), ("I_DJNZ", 1), ("I_CPL", 1), ("I_CCF", 1), ("I_SCF", 1),
        ("I_RETN", 1), ("I_BT", 1), ("I_BC", 1), ("I_BTR", 1), ("I_RLD", 1),
        ("I_RRD", 1), ("I_INRC", 1), ("SetDI", 1), ("SetEI", 1), ("IMode", 2),
        ("Halt", 1), ("NoRead", 1), ("Write", 1)]


def rng(w):
    return "" if w == 1 else "[%d:0] " % (w - 1)


def miter():
    L = ["// generated by make_child.py. Mode = 1 on both sides, see the docstring.",
         "module child_miter ("]
    L += ["    input wire %s%s," % (rng(w), n) for n, w in INS]
    L[-1] = L[-1].rstrip(",")
    L += [");"]
    for n, w in OUTS:
        L.append("    wire %sg_%s, t_%s;" % (rng(w), n, n))
    conn_in = ", ".join(".%s(%s)" % (n, n) for n, _ in INS)
    for tag, mod in (("g", "tv80_mcode_gold"), ("t", "tv80_mcode_gate")):
        L.append("    %s #(.Mode(1)) u_%s (" % (mod, tag))
        L.append("        %s," % conn_in)
        L += ["        .%s(%s_%s)," % (n, tag, n) for n, _ in OUTS]
        L[-1] = L[-1].rstrip(",")
        L.append("    );")
    L.append("`ifdef FORMAL")
    L.append("    always @* begin")
    L.append("`ifdef ASSUME_INV")
    L.append("        // The parent's reachable-state invariant, discharged separately")
    L.append("        // on tv80_core by parent.sby (R90). Assumed here, never asserted.")
    L.append("        assume (!(MCycle[5] && MCycle[6]));")
    L.append("`endif")
    for n, _ in OUTS:
        L.append("        eq_%s: assert (g_%s == t_%s);" % (n, n, n))
    L.append("    end")
    L.append("`endif")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def broken():
    src = io.open(os.path.join(HERE, "gate_mcode.v"), encoding="utf-8").read()
    anchor = "2'b01 : \n              begin\n                Inc_PC = 1'b1;"
    if src.count(anchor) != 1:
        raise SystemExit("broken-variant anchor not found exactly once (%d)" % src.count(anchor))
    return src.replace(anchor, anchor.replace("Inc_PC = 1'b1;", "Inc_PC = 1'b0;"), 1)


def sby():
    return """[tasks]
plain
inv
broken

[options]
mode prove

[engines]
smtbmc yices

[script]
plain: read_verilog -formal gold_mcode.v gate_mcode.v child_miter.sv
inv: read_verilog -formal -DASSUME_INV gold_mcode.v gate_mcode.v child_miter.sv
broken: read_verilog -formal -DASSUME_INV gold_mcode.v broken_mcode.v child_miter.sv
prep -top child_miter

[files]
gold_mcode.v
gate_mcode.v
broken_mcode.v
child_miter.sv
"""


def main():
    io.open(os.path.join(HERE, "child_miter.sv"), "w", encoding="utf-8", newline="\n").write(miter())
    io.open(os.path.join(HERE, "broken_mcode.v"), "w", encoding="utf-8", newline="\n").write(broken())
    io.open(os.path.join(HERE, "child.sby"), "w", encoding="utf-8", newline="\n").write(sby())
    print("child_miter.sv: %d inputs, %d outputs asserted, Mode = 1" % (len(INS), len(OUTS)))
    print("broken_mcode.v: Inc_PC forced to 0 in the 2'b01 arm")
    print("child.sby: tasks plain, inv, broken")


if __name__ == "__main__":
    main()
